#include<iostream>
using namespace std;
int main() {
    // practice of operators in c++;
int a=3, b=6;
cout<<a+b<<endl;
cout<<a-b<<endl;
cout<<a/b<<endl;
cout<<a*b<<endl;
cout<<a%b<<endl;
cout<<a++<<endl;
cout<<b--<<endl;
cout<<++a<<endl;
cout<<--b<<endl;

int c=3,d=0;
// practice of comparison operators in c++;
cout<<"the value of c==d is "<<(c==d)<<endl;
cout<<"the value of c!=d is "<<(c!=d)<<endl;
cout<<"the value of c>d is "<<(c>d)<<endl;
cout<<"the value of c<d is "<<(c<d)<<endl;
cout<<"the value of c>=d is "<<(c>=d)<<endl;
cout<<"the value of c<=d is "<<(c<=d)<<endl;



    return 0;
}

